// Bundles the N1 content bank into project/n1-content.js, the one data file the N1 screens read (through n1.js).
// usage: node tools/build-content.mjs        (from yaoki-n1/; run it after changing anything in content/)
// Reads content/syllabus.json (units and the order of lessons), content/lessons/*.json, content/kanji.json and
// content/mocks/*.json. A lesson the syllabus lists but that has no file yet is left out, and said so.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const C = path.join(HERE, '..', 'content');
const OUT = path.join(HERE, '..', 'project', 'n1-content.js');
const read = (f) => JSON.parse(fs.readFileSync(f, 'utf8'));

const syllabus = read(path.join(C, 'syllabus.json'));
const units = syllabus.weeks.map((w) => ({ n: w.n, ja: w.ja, en: w.en }));
const lessons = [];
const missing = [];
for (const w of syllabus.weeks) {
  for (const d of w.days) {
    const id = `u${w.n}l${d.d}`;
    const f = path.join(C, 'lessons', id + '.json');
    if (!fs.existsSync(f)) { missing.push(id); continue; }
    const l = read(f);
    lessons.push({ id, unit: w.n, lesson: d.d, contrast: d.contrast || '', grammar: l.grammar, vocab: l.vocab, reading: l.reading, listening: l.listening });
  }
}
const kanji = read(path.join(C, 'kanji.json')).kanji;
const mocksDir = path.join(C, 'mocks');
const mocks = fs.existsSync(mocksDir) ? fs.readdirSync(mocksDir).filter((f) => f.endsWith('.json')).sort().map((f) => read(path.join(mocksDir, f))) : [];

const data = { units, lessons, kanji, mocks };
fs.writeFileSync(OUT, `/* Generated by tools/build-content.mjs from content/. Do not edit: change the content files and run it again.
 * Kanji data: KANJIDIC2 and JMdict (EDRDG, CC BY-SA 4.0). */
window.__ykN1 = ${JSON.stringify(data)};
`);
console.log(`n1-content.js: ${units.length} units, ${lessons.length} lessons, ${kanji.length} kanji, ${mocks.length} mocks, ${fs.statSync(OUT).size} bytes` + (missing.length ? `; no file yet for ${missing.length} lessons (${missing.slice(0, 6).join(', ')}${missing.length > 6 ? ', …' : ''})` : ''));
