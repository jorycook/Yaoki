// Bundles the N1 content bank into project/n1-content.js, the one data file the N1 screens read (through n1.js).
// usage: node tools/build-content.mjs        (from yaoki-n1/; run it after changing anything in content/)
// Reads content/syllabus.json (units and the order of lessons), content/lessons/*.json, content/kanji.json and
// content/mocks/*.json. A lesson the syllabus lists but that has no file yet is left out, and said so.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { makeReview } from './make-review.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const C = path.join(HERE, '..', 'content');
const OUT = path.join(HERE, '..', 'project', 'n1-content.js');
const read = (f) => JSON.parse(fs.readFileSync(f, 'utf8'));

const bank = (dir, n) => { const f = path.join(C, dir, `u${n}.json`); return fs.existsSync(f) ? read(f) : null; };
const syllabus = read(path.join(C, 'syllabus.json'));
const units = syllabus.weeks.map((w) => ({ n: w.n, ja: w.ja, en: w.en }));
const lessons = [];
const missing = [];
for (const w of syllabus.weeks) {
  for (const d of w.days) {
    const id = `u${w.n}l${d.d}`;
    const f = path.join(C, 'lessons', id + '.json');
    if (!fs.existsSync(f)) { missing.push(id); continue; }
    const l = read(f);
    /* the banks (BANKS.md): fifteen more words, a longer reading and a longer listening item for the lesson, when written */
    const words = bank('words', w.n), reading = bank('reading', w.n), listening = bank('listening', w.n);
    lessons.push({
      id, unit: w.n, lesson: d.d, contrast: d.contrast || '', grammar: l.grammar, vocab: l.vocab, reading: l.reading, listening: l.listening,
      vocab2: words && words.lessons && words.lessons[String(d.d)] || [],
      reading2: reading && reading.items && reading.items[d.d - 1] || null,
      listening2: listening && listening.items && listening.items[d.d - 1] || null,
    });
  }
}
const kanji = read(path.join(C, 'kanji.json')).kanji;
const mocksDir = path.join(C, 'mocks');
const mocks = fs.existsSync(mocksDir) ? fs.readdirSync(mocksDir).filter((f) => f.endsWith('.json')).sort().map((f) => read(path.join(mocksDir, f))) : [];

/* the review of the earlier levels: the N2 grammar (review-n2.json, or its parts while it is written), the N2 to N4
   course questions, and the N2 kanji */
const n2 = fs.existsSync(path.join(C, 'review-n2.json')) ? read(path.join(C, 'review-n2.json')).patterns
  : fs.existsSync(path.join(C, 'review-n2')) ? fs.readdirSync(path.join(C, 'review-n2')).filter((f) => /^part\d+\.json$/.test(f)).sort((a, b) => parseInt(a.slice(4)) - parseInt(b.slice(4))).flatMap((f) => read(path.join(C, 'review-n2', f)).patterns) : [];
const review = { n2, items: makeReview(), kanji: fs.existsSync(path.join(C, 'kanji-review.json')) ? read(path.join(C, 'kanji-review.json')).kanji : [] };
const data = { units, lessons, kanji, mocks, review };
fs.writeFileSync(OUT, `/* Generated by tools/build-content.mjs from content/. Do not edit: change the content files and run it again.
 * Kanji data: KANJIDIC2 and JMdict (EDRDG, CC BY-SA 4.0). */
window.__ykN1 = ${JSON.stringify(data)};
`);
const n = (k) => lessons.filter((l) => l[k] && (!Array.isArray(l[k]) || l[k].length)).length;
console.log(`n1-content.js: ${units.length} units, ${lessons.length} lessons (${n('vocab2')} with their word bank, ${n('reading2')} with a longer reading, ${n('listening2')} with a longer listening), ${kanji.length} kanji, ${mocks.length} mocks, review: ${review.n2.length} N2 patterns, ${review.items.length} course questions, ${review.kanji.length} N2 kanji; ${fs.statSync(OUT).size} bytes` + (missing.length ? `; no file yet for ${missing.length} lessons (${missing.slice(0, 6).join(', ')}${missing.length > 6 ? ', …' : ''})` : ''));
