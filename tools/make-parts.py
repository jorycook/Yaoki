#!/usr/bin/env python3
"""The parts of each kanji, for the kanji parts puzzle (漢字パズル), made from KanjiVG.

usage: python3 tools/make-parts.py [--kanjivg DIR] [--check]

Writes yaoki/project/kanji-parts.js: for every kanji of the main app's strokes.js (the kanji of the scene words, かな
to N2) that KanjiVG splits into two parts, the two parts in stroke order:

    window.__ykParts = { "語": [["言", [0,1,2,3,4,5,6], [x0,y0,x1,y1]], ["吾", [7,…,13], [x0,y0,x1,y1]]], … }

Each part is its element as KanjiVG names it ("" when it has no name), the numbers of its strokes in strokes.js
(counted from 0), and the box its strokes take up in KanjiVG's 109 × 109 box, so the puzzle can draw a part on its own
tile, centred, and then in its place in the kanji. A part KanjiVG cuts in two (囗 around 玉 in 国, its last stroke
closing the box) is one part with all its strokes. Kanji that are one piece (人, 木) or split three ways or more
(両, 年) are left out.

KanjiVG (https://kanjivg.tagaini.net, by Ulrich Apel and contributors) is under the Creative Commons Attribution-Share
Alike 3.0 licence, and so is the data made from it here. It is read from the cache tools/make-strokes.py fills
(~/.cache/yaoki/kanjivg-<release>), or from --kanjivg DIR.

--check only reports whether kanji-parts.js is there and every kanji in it has its strokes (the app build calls it).
"""
import json
import os
import re
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import importlib.util
_spec = importlib.util.spec_from_file_location('make_strokes', os.path.join(HERE, 'make-strokes.py'))
make_strokes = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(make_strokes)

STROKES = os.path.join(ROOT, 'yaoki', 'project', 'strokes.js')
OUT = os.path.join(ROOT, 'yaoki', 'project', 'kanji-parts.js')
SVG = '{http://www.w3.org/2000/svg}'
KVG = '{http://kanjivg.tagaini.net}'

HEAD = ('/* The parts of each kanji, for the kanji parts puzzle. Generated by tools/make-parts.py; do not edit, run it again.\n'
        ' * For each kanji of strokes.js that splits into two parts: each part\'s element, the numbers of its strokes in\n'
        ' * strokes.js (from 0) and the box they take up in KanjiVG\'s 109 x 109 box.\n'
        ' * Made from KanjiVG %s (https://kanjivg.tagaini.net), by Ulrich Apel and contributors, under the\n'
        ' * Creative Commons Attribution-Share Alike 3.0 licence (https://creativecommons.org/licenses/by-sa/3.0/);\n'
        ' * this data is available under the same licence. */\n') % make_strokes.RELEASE

NUM = re.compile(r'-?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?')


def path_points(d):
    """every point a KanjiVG path passes through or bends towards (end points and control points), absolute: enough for
    the box a stroke takes up, a control point at most a little outside the curve itself"""
    pts = []
    x = y = 0.0
    sx = sy = 0.0
    for m in re.finditer(r'([MmCcSsLlHhVvQqTtZz])([^MmCcSsLlHhVvQqTtZz]*)', d):
        cmd, args = m.group(1), [float(n) for n in NUM.findall(m.group(2))]
        rel = cmd.islower()
        c = cmd.upper()
        if c == 'Z':
            x, y = sx, sy
            continue
        step = {'M': 2, 'L': 2, 'T': 2, 'H': 1, 'V': 1, 'C': 6, 'S': 4, 'Q': 4}[c]
        for i in range(0, len(args) - step + 1, step):
            a = args[i:i + step]
            if c == 'H':
                x = x + a[0] if rel else a[0]
                pts.append((x, y))
                continue
            if c == 'V':
                y = y + a[0] if rel else a[0]
                pts.append((x, y))
                continue
            ox, oy = (x, y) if rel else (0.0, 0.0)
            for j in range(0, step, 2):
                pts.append((ox + a[j], oy + a[j + 1]))
            x, y = ox + a[-2], oy + a[-1]
            if c == 'M' and i == 0:
                sx, sy = x, y
    return pts


def strokes_kanji():
    with open(STROKES, encoding='utf-8') as f:
        text = f.read()
    out = {}
    for c, paths in re.findall(r'^"(.)":"([^"]*)"', text, re.M):
        if make_strokes.is_kanji(c):
            out[c] = paths.split('|')
    return out


def parts_of(folder, c):
    path = os.path.join(folder, '%05x.svg' % ord(c))
    if not os.path.isfile(path):
        return None
    root = ET.parse(path).getroot()
    holder = None
    for g in root.iter(SVG + 'g'):
        if g.get('id', '').startswith('kvg:StrokePaths'):
            holder = g
            break
    if holder is None or not len(holder):
        return None
    top = list(holder)[0]
    if any(ch.tag == SVG + 'path' for ch in top):
        return None
    groups = [ch for ch in top if ch.tag == SVG + 'g']
    # a part cut in two (kvg:part 1 and 2, or the same element twice around another) is one part
    merged = []
    for g in groups:
        el = g.get(KVG + 'element') or ''
        nums = []
        for p in g.iter(SVG + 'path'):
            m = re.search(r'-s(\d+)$', p.get('id', ''))
            if m:
                nums.append(int(m.group(1)) - 1)
        same = next((x for x in merged if el and x['el'] == el), None)
        if same is not None:
            same['strokes'] += nums
        else:
            merged.append({'el': el, 'strokes': nums})
    if len(merged) != 2 or not all(x['strokes'] for x in merged):
        return None
    every = sorted(merged[0]['strokes'] + merged[1]['strokes'])
    return merged, every


def box(paths, nums):
    pts = []
    for n in nums:
        pts += path_points(paths[n])
    xs = [p[0] for p in pts]
    ys = [p[1] for p in pts]
    return [round(min(xs), 1), round(min(ys), 1), round(max(xs), 1), round(max(ys), 1)]


def check():
    if not os.path.isfile(OUT):
        sys.exit('make-parts: %s is missing (python3 tools/make-parts.py makes it)' % os.path.relpath(OUT, ROOT))
    with open(OUT, encoding='utf-8') as f:
        text = f.read()
    data = json.loads(re.search(r'window\.__ykParts = (\{.*\});', text, re.S).group(1))
    have = strokes_kanji()
    bad = [k for k, ps in data.items() if k not in have or max(max(p[1]) for p in ps) >= len(have[k])]
    if bad:
        sys.exit('make-parts: parts for kanji whose strokes differ from strokes.js: ' + ''.join(bad[:40]) + ' (run tools/make-parts.py)')
    print('make-parts: %d kanji with their two parts' % len(data))


def main():
    args = sys.argv[1:]
    if '--check' in args:
        return check()
    given = args[args.index('--kanjivg') + 1] if '--kanjivg' in args else None
    folder = make_strokes.kanjivg_dir(given)
    have = strokes_kanji()
    data = {}
    for c in sorted(have, key=ord):
        got = parts_of(folder, c)
        if not got:
            continue
        merged, every = got
        paths = have[c]
        if every != list(range(len(paths))):
            continue
        data[c] = [[x['el'], sorted(x['strokes']), box(paths, x['strokes'])] for x in merged]
    lines = ['"%s":%s' % (k, json.dumps(v, ensure_ascii=False, separators=(',', ':'))) for k, v in data.items()]
    text = HEAD + 'window.__ykParts = {\n' + ',\n'.join(lines) + '\n};\n'
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(text)
    print('make-parts: %d of %d kanji split into two parts -> %s (%d bytes)' % (len(data), len(have), os.path.relpath(OUT, ROOT), len(text.encode('utf-8'))))


if __name__ == '__main__':
    main()
