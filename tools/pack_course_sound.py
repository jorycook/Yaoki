"""Pack the course clips (made by course_clips.py) into yaoki/project/sound-course.js, which sound.js plays.
usage: python3 tools/pack_course_sound.py <clip folder with manifest.json> [n2|n5]   (n2 writes sound-course.js; other levels one file per unit, sound-course-<level>-uNN.js)"""
import base64, json, os, sys
src = sys.argv[1]
lv = sys.argv[2] if len(sys.argv) > 2 else 'n2'
m = json.load(open(os.path.join(src, 'manifest.json'), encoding='utf-8'))
here = os.path.dirname(os.path.abspath(__file__))
course = open(os.path.join(here, '..', 'yaoki', 'project', 'course-' + lv + '.js'), encoding='utf-8').read()
import re
# only clips the course still names; a mini mock's parts are named after their item (n5mock10_q)
def named(k):
    mm = re.match(r'^(n\d+mock\d+)_\w+$', k)
    return ('"' + k + '"') in course or bool(mm and ('"' + mm.group(1) + '"') in course)
keys = sorted(k for k in m if named(k))
def unit_of(k):
    m = re.search(r'n\d+u0?(\d+)', k)
    return int(m.group(1)) if m else 0
import re
groups = {0: keys} if lv == 'n2' else {}
if lv != 'n2':
    for k in keys: groups.setdefault(unit_of(k), []).append(k)
outs = []
for unit, ks in sorted(groups.items()):
  lines = ['/* Yaoki course sound: the teach examples, scene words and listening lessons of the written days. Synthetic voices, MP3 as base64. Generated by tools/pack_course_sound.py. Played by sound.js. */',
           '(function () {', 'var c = window.__ykClips = window.__ykClips || {};']
  for k in ks:
    b = base64.b64encode(open(os.path.join(src, k + '.mp3'), 'rb').read()).decode('ascii')
    lines.append("c['%s'] = { ms: %d, b: '%s' };" % (k, m[k]['ms'], b))
  lines.append('})();')
  # N2's clips are one file loaded with the page; other levels have one file per unit, loaded when that unit is in use (course.js)
  name = 'sound-course.js' if lv == 'n2' else 'sound-course-%s-u%02d.js' % (lv, unit)
  out = os.path.join(here, '..', 'yaoki', 'project', name)
  open(out, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
  outs.append((name, len(ks), os.path.getsize(out) // 1024))
name = ', '.join('%s %d clips %d KB' % o for o in outs)
missing = sorted(set(__import__('re').findall(r'"clip":"([^"]+)"', course)) - set(m) - {'t_ex1', 't_ex2'} - {k for k in __import__('re').findall(r'"clip":"(s_(?:resid|cert|reissue|ticket|form|sample|fee|ident))"', course)})
print(name + '; %d clips, %.1f s; named in the course but not made yet: %s' % (len(keys), sum(m[k]['ms'] for k in keys) / 1000, ', '.join(missing) or 'none'))
