"""Pack the course clips (made by course_clips.py) into yaoki/project/sound-course.js, which sound.js plays.
usage: python3 tools/pack_course_sound.py <clip folder with manifest.json>"""
import base64, json, os, sys
src = sys.argv[1]
m = json.load(open(os.path.join(src, 'manifest.json'), encoding='utf-8'))
here = os.path.dirname(os.path.abspath(__file__))
course = open(os.path.join(here, '..', 'yaoki', 'project', 'course-n2.js'), encoding='utf-8').read()
keys = sorted(k for k in m if ('"' + k + '"') in course)   # only clips the course still names
lines = ['/* Yaoki course sound: the teach examples, scene words and listening lessons of the written days. Synthetic voices, MP3 as base64. Generated by tools/pack_course_sound.py. Played by sound.js. */',
         '(function () {', 'var c = window.__ykClips = window.__ykClips || {};']
for k in keys:
    b = base64.b64encode(open(os.path.join(src, k + '.mp3'), 'rb').read()).decode('ascii')
    lines.append("c['%s'] = { ms: %d, b: '%s' };" % (k, m[k]['ms'], b))
lines.append('})();')
out = os.path.join(here, '..', 'yaoki', 'project', 'sound-course.js')
open(out, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
missing = sorted(set(__import__('re').findall(r'"clip":"([^"]+)"', course)) - set(m) - {'t_ex1', 't_ex2'} - {k for k in __import__('re').findall(r'"clip":"(s_(?:resid|cert|reissue|ticket|form|sample|fee|ident))"', course)})
print('sound-course.js: %d clips, %.1f s, %d KB; named in the course but not made yet: %s' % (len(keys), sum(m[k]['ms'] for k in keys) / 1000, os.path.getsize(out) // 1024, ', '.join(missing) or 'none'))
