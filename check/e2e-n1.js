// Full click-through of the N1 app (YK_LEVEL=N1 bash run-app.sh e2e-n1.js): the flow of e2e.js with the N1 lessons.
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');
const { openBoard, inspect, site, out } = require('./rt-check.js');
const { clips } = require('./level.js');

(async () => {
  const fontsCss = fs.readFileSync(path.join(site, 'fonts.css'), 'utf8');
  const browser = await chromium.launch();
  const { page, logs } = await openBoard(browser, 'App.dc.html', fontsCss);
  const startUrl = page.url();
  let fails = 0;
  const ok = (cond, msg) => { if (!cond) { fails += 1; console.log('  FAIL: ' + msg); } };
  const click = async (sel, wait = 450) => { await page.locator(sel).first().click({ timeout: 5000 }); await page.waitForTimeout(wait); };
  const h1 = async () => ((await page.locator('h1').first().textContent()) || '').replace(/\s+/g, ' ').trim();
  const has = async (text) => (await page.getByText(text, { exact: false }).count()) > 0;
  // SOUND: the clips really play (default). With NOSOUND=1, HELDBACK=1 or BADCLIPS=1 the screens must fall back to their silent stand-in.
  const SOUND = !process.env.NOSOUND && !process.env.HELDBACK && !process.env.BADCLIPS;
  const unlocked = () => page.waitForFunction(() => document.querySelectorAll('button[aria-pressed]:not([disabled])').length === 3, null, { timeout: 25000 });
  const played = async () => (await page.evaluate(() => window.__audio)).filter((a) => a.ev === 'start').map((a) => a.d);
  const near = (list, ms) => list.some((d) => Math.abs(d - ms) < 120);
  const at = async (name, expectH1) => {
    const t = await page.locator('h1').count() ? await h1() : '(no h1)';
    const info = await inspect(page);
    await page.screenshot({ path: path.join(out, 'e2e-' + name + '.png') });
    const bad = info.errors.length || info.issues.length || info.unresolved;
    console.log(`${name}: h1="${t}" root=${info.rootH}` + (bad ? ' PROBLEMS ' + JSON.stringify({ e: info.errors, i: info.issues, u: info.unresolved }) : ''));
    if (expectH1) ok(t.includes(expectH1), `${name}: expected h1 to include "${expectH1}"`);
    ok(!bad, name + ': layout or runtime problems');
    ok(page.url() === startUrl, name + ': the frame navigated away to ' + page.url());
  };

  await at('01-goal', '目標を決めよう');
  ok((await page.locator('button:has-text("N2")').count()) === 0, 'goal: N5 to N2 belong to their own app and should not be offered');
  await click('button:has-text("N1")'); await click('button:has-text("60分")'); await click('button:has-text("45分")');
  await click('button:has-text("Paint the first eye")');
  await at('02-goal-painted', '目標を決めよう');
  await click('a:has-text("Start")', 700);
  await at('03-main');
  ok(await has('原因・理由'), 'main: week banner missing');
  ok((await page.locator('text=17').count()) > 0, 'main: stamp count 17 missing');
  await click('a:has-text("はじめる")', 700);
  await at('04-today-fresh', '〜とあって・〜ゆえに');
  await click('a:has-text("Start with the teach page")', 700);
  await at('05-teach', '〜とあって');
  await click('button[aria-label="Play example 2"]', 400);
  if (SOUND) ok(near(await played(), clips.t_ex2), 'teach: example 2 should have played, got ' + JSON.stringify(await played()));
  await click('a:has-text("Next")', 700);
  await at('06-compare', 'どれを使う');
  await click('button:has-text("とあって")'); await click('button:has-text("ゆえに")');
  await click('a:has-text("Start the drill")', 700);
  await at('07-drill-fresh');
  ok((await page.locator('button[disabled]').count()) === 1, 'drill: Check should start disabled');
  await click('button:has-text("とあれば")'); await click('button:has-text("Check")', 600);
  await at('08-drill-wrong');
  ok(await has('Saved to your mistake notebook'), 'drill: saved line missing');
  await click('a:has-text("つぎへ")', 700);
  await at('09-star-fresh', '★に入るのはどれ');
  await click('role=button[name=/^が$/]'); await click('role=button[name=/^ゆえに$/]'); await click('role=button[name=/^周囲の$/]'); await click('role=button[name=/^助けを$/]');
  await click('button:has-text("Check")', 600);
  await at('10-star-correct', '★に入るのはどれ');
  ok(await has('せいかい'), 'star: expected correct verdict');
  await click('a:has-text("つぎへ")', 700);
  await at('11-today-exam-open', '〜とあって・〜ゆえに');
  ok((await page.locator('[aria-label="Lesson done"]').count()) === 0, 'today: grammar is not done before the exam-style step');
  await click('a:has-text("Start exam-style")', 700);
  await at('12-exam-q1');
  ok(await has('EXAM-STYLE'), 'exam: strip missing');
  ok((await page.locator('button[disabled]').count()) === 1, 'exam: Next should start disabled');
  const clock0 = await page.locator('text=/^\\d:\\d\\d$/').first().textContent();
  await page.waitForTimeout(1300);
  const clock1 = await page.locator('text=/^\\d:\\d\\d$/').first().textContent();
  ok(clock0 !== clock1, `exam: the clock should count down (${clock0} -> ${clock1})`);
  await click('button[aria-pressed]:has-text("とあって")'); await click('button:has-text("Next")', 500);
  await at('12-exam-q2');
  await click('button[aria-pressed]:has-text("とあって")'); await click('button:has-text("Next")', 500);
  await at('12-exam-q3');
  await click('button[aria-pressed]:has-text("店の")'); await click('button:has-text("Finish")', 700);
  await at('13-exam-result', '2');
  ok(await has('人間は弱い存在'), 'exam result: question 2 row missing');
  ok(await has('1 mistake saved to your notebook'), 'exam result: saved line missing');
  await click('a:has-text("つぎへ")', 700);
  await at('14-today-grammar-done', '〜とあって・〜ゆえに');
  ok((await page.locator('[aria-label="Lesson done"]').count()) === 1, 'today: one lesson should be done');
  await click('a:has-text("Station notices")', 700);
  await at('15-scene', '駅の掲示');
  await click('button:has-text("払い戻し")'); await click('button:has-text("入場規制")');
  await click('button[aria-label="Play the word"]', 400);
  if (SOUND) ok(near(await played(), clips.s_limit), 'scene: 入場規制 should have played, got ' + JSON.stringify(await played()));
  ok(await has('5 of 8 found'), 'scene: count should be 5 of 8');
  await click('button:has-text("1 ふっきゅう")', 500);
  await at('16-scene-answered', '駅の掲示');
  await click('a:has-text("つぎへ")', 700);
  await at('17-today-two-done', '〜とあって・〜ゆえに');
  ok((await page.locator('[aria-label="Lesson done"]').count()) === 2, 'today: two lessons should be done');
  await click('a:has-text("writer")', 700);
  await at('18-reading-fresh');
  await page.waitForTimeout(1200);
  await click('button[aria-pressed] >> nth=0'); await click('button:has-text("Check")', 600);
  await at('19-reading-wrong');
  ok(await has('Option 1 goes too far'), 'reading: specific explanation missing');
  await click('a:has-text("つぎへ")', 900);
  await at('20-today-all-done', '〜とあって・〜ゆえに');
  ok(await has('4日目 完了'), 'today: day-done banner missing');
  await click('a:has-text("もどる")', 900);
  await at('21-main-day-done');
  ok((await page.locator('text=18').count()) > 0, 'main: stamp count should be 18');
  ok(await has('DONE TODAY'), 'main: done callout missing');
  await click('a[aria-label="Day 7, week test"]', 900);
  await at('22-weektest');
  ok(await has('よく'), 'week test: stamp missing');
  await click('a:has-text("Review mistakes")', 700);
  await at('23-notebook', '間違いノート');
  let nb = (await page.locator('body').textContent()).replace(/\s+/g, ' ');
  ok(nb.includes('筆者の主張') && nb.includes('効率化は時間のむだ'), 'notebook: reading mistake missing');
  ok(nb.includes('人間は弱い存在') && nb.includes('文の文法1'), 'notebook: exam-style mistake missing');
  ok(nb.includes('花火大会') && nb.includes('とあれば'), 'notebook: drill mistake missing');
  ok(!nb.includes('文の文法2'), 'notebook: star and exam question 3 were answered correctly, should not be listed');
  await click('a:has-text("Review now")', 700);
  await at('24-review-kanji');
  ok((await page.locator('button[disabled]').count()) === 1, 'review: Next should start disabled');
  await click('button[aria-pressed]:has-text("ほっそく")', 500);
  await at('24-review-kanji-right');
  ok(await has('2 of 3 in a row'), 'review: step note missing');
  await click('button:has-text("Next")', 500);
  await at('25-review-listen');
  ok((await page.locator('button[aria-pressed][disabled]').count()) === 3, 'review: answers should be locked until the audio has played');
  let t0 = Date.now();
  await click('button[aria-label="Play audio"]', 300);
  await unlocked();
  console.log('   review clip took ' + (Date.now() - t0) + ' ms');
  if (SOUND) ok(near(await played(), clips.r_item) && Date.now() - t0 > clips.r_item - 480, 'review: the clip should have played in full');
  else ok(Date.now() - t0 < 4500, 'review: without sound the stand-in should be short');
  await click('button[aria-pressed] >> nth=1', 500);
  await at('25-review-listen-right');
  ok(await has('3 of 3 in a row'), 'review: cleared note missing');
  await click('button:has-text("Finish")', 900);
  await at('26-review-summary', '復習おわり');
  await click('a:has-text("Back to the notebook")', 900);
  await at('27-notebook-caught-up', '間違いノート');
  nb = (await page.locator('body').textContent()).replace(/\s+/g, ' ');
  ok(nb.includes('all caught up'), 'notebook: caught-up card missing');
  ok(nb.includes('Cleared today'), 'notebook: cleared row missing');
  ok(nb.includes('in 7 days'), 'notebook: the reviewed kanji should now be 7 days out');
  ok(!nb.includes('Review now'), 'notebook: review button should be gone');
  await click('nav a:has-text("Mock exam")', 700);
  await at('28-mock', '模擬試験');
  ok(await has('ミニ模試'), 'mock: mini mock card missing');
  ok((await page.locator('[aria-label^="Locked."]').count()) === 2, 'mock: both full mocks should be locked');
  await click('nav a:has-text("Readiness")', 700);
  await at('29-readiness', '合格判定');
  await click('a:has-text("Drill")', 700);
  await at('30-listening-fresh', 'いちばんいい返事は');
  t0 = Date.now();
  await click('button[aria-label="Play audio"]', 300);
  await unlocked();
  console.log('   drill clip took ' + (Date.now() - t0) + ' ms');
  if (SOUND) ok(near(await played(), clips.l_drill) && Date.now() - t0 > clips.l_drill - 490, 'listening: the clip should have played in full');
  else ok(Date.now() - t0 < 4500, 'listening: without sound the stand-in should be short');
  await click('button[aria-pressed] >> nth=0', 600);
  await at('31-listening-correct', 'いちばんいい返事は');
  ok(await has('3問連続正解'), 'listening: streak chip missing');
  await click('a:has-text("つぎへ")', 700);
  await at('32-readiness-back', '合格判定');
  await click('nav a:has-text("Notebook")', 600);
  await at('33-notebook-still-caught-up', '間違いノート');
  ok(await has('all caught up'), 'notebook: review state lost after tab switches');
  await click('nav a:has-text("Path")', 700);
  await at('34-main-again');
  ok(await has('DONE TODAY'), 'main: shared state lost after tab switches');

  const noisy = logs.filter((l) => !/Download the React DevTools/.test(l));
  console.log('clips started (ms): ' + JSON.stringify(await played()));
  if (!SOUND) ok((await played()).length === 0, 'no clip should start when sound is off');
  console.log('console problems: ' + JSON.stringify(noisy.slice(0, 10)));
  console.log((SOUND ? 'with sound: ' : 'silent fallback: ') + (fails === 0 && noisy.length === 0 ? 'E2E PASS' : `E2E FAIL (${fails} failed checks, ${noisy.length} console problems)`));
  await browser.close();
})().catch((e) => { console.error('E2E CRASH', e); process.exit(1); });
