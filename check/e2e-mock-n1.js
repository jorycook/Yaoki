// Click-through of the N1 mini mock (YK_LEVEL=N1 bash run-app.sh e2e-mock-n1.js): the run of e2e-mock.js with the N1 paper.
const fs = require('fs');
const path = require('path');
const { chromium } = require('playwright');
const { openBoard, inspect, site, out } = require('./rt-check.js');
const { mockClips, listeningMs } = require('./level.js');

(async () => {
  const fontsCss = fs.readFileSync(path.join(site, 'fonts.css'), 'utf8');
  const browser = await chromium.launch();
  const { page, logs } = await openBoard(browser, 'TShell.dc.html?screen=Mock', fontsCss);
  const startUrl = page.url();
  let fails = 0;
  const ok = (cond, msg) => { if (!cond) { fails += 1; console.log('  FAIL: ' + msg); } };
  const click = async (sel, wait = 400) => { await page.locator(sel).first().click({ timeout: 5000 }); await page.waitForTimeout(wait); };
  const body = async () => ((await page.locator('body').textContent()) || '').replace(/\s+/g, ' ');
  const has = async (text) => (await body()).includes(text);
  const at = async (name) => {
    const info = await inspect(page);
    await page.screenshot({ path: path.join(out, 'mk-' + name + '.png') });
    const issues = info.issues;
    const bad = info.errors.length || issues.length || info.unresolved;
    console.log(`${name}: root=${info.rootH}` + (bad ? ' PROBLEMS ' + JSON.stringify({ e: info.errors, i: issues, u: info.unresolved }) : ''));
    ok(!bad, name + ': layout or runtime problems');
    ok(page.url() === startUrl, name + ': the frame navigated away to ' + page.url());
  };
  const pickOpt = (n) => click(`button[aria-pressed] >> nth=${n - 1}`, 150);
  // SOUND: the clips really play (default). With NOSOUND=1, HELDBACK=1 or BADCLIPS=1 the run must fall back to timing alone.
  const SOUND = !process.env.NOSOUND && !process.env.HELDBACK && !process.env.BADCLIPS;
  const until = (text, ms) => page.waitForFunction((t) => document.body.textContent.includes(t), text, { timeout: ms });
  const audio = () => page.evaluate(() => window.__audio);

  await at('01-tab');
  ok(await has('ミニ模試'), 'tab: mini mock card missing');
  ok(await has('約100問'), 'tab: the full paper should be listed at about 100 questions');
  ok(!(await has('Last result')), 'tab: should not show a result before a run');
  // a first run that is abandoned leaves nothing behind
  await click('a:has-text("Start")', 600);
  await click('button:has-text("Start section 1")', 400);
  await click('button[aria-label="Quit the mock"]', 400);
  await click('a:has-text("Quit")', 600);
  ok(await has('約100問'), 'quit: should land back on the mock tab');
  ok(!(await has('Last result')), 'tab: a first run that was quit should leave no result');
  await click('a:has-text("Start")', 600);
  await at('02-briefing');
  ok(await has('HOW IT RUNS'), 'briefing: rules missing');
  ok(await has('Mini mock · N1'), 'briefing: level missing');
  await click('button:has-text("Start section 1")', 500);
  await at('03-s1-q1');
  ok(await has('漢字読み'), 's1: first item type missing');
  const c0 = await page.locator('[role=timer]').first().textContent();
  await page.waitForTimeout(1300);
  const c1 = await page.locator('[role=timer]').first().textContent();
  ok(c0 !== c1, `s1: the clock should count down (${c0} -> ${c1})`);
  // section 1, nine questions: 1, 1 (wrong), 3, 3, flag + 3 (wrong), 3, 2, 2, then 9 left blank at first
  await pickOpt(1); await click('button:has-text("Next")');
  await pickOpt(1); await click('button:has-text("Next")');
  ok(await has('言い換え類義'), 's1: question 3 should be 言い換え類義');
  await pickOpt(3); await click('button:has-text("Next")');
  await pickOpt(3); await click('button:has-text("Next")');
  await click('button:has-text("Flag")', 150); await pickOpt(3);
  await at('04-s1-q5');
  await click('button:has-text("Previous")'); await click('button:has-text("Next")');
  await click('button:has-text("Next")');
  await pickOpt(3); await click('button:has-text("Next")');
  ok(await has('文章の文法'), 's1: question 7 should be 文章の文法');
  await pickOpt(2); await click('button:has-text("Next")');
  await at('05-s1-passage');
  ok(await has('内容理解（短文）'), 's1: question 8 should be the short passage');
  await pickOpt(2); await click('button:has-text("Next")');
  await at('06-s1-pair');
  ok(await has('統合理解'), 's1: question 9 should be 統合理解');
  await click('button:has-text("Answer sheet")', 500);
  await at('07-s1-sheet');
  ok(await has('8 / 9 answered'), 'sheet: should count 8 answered');
  ok(await has('未解答が1問あります'), 'sheet: one blank expected');
  ok((await page.locator('svg[aria-label="Flagged"]').count()) === 1, 'sheet: one flag expected');
  await click('button[aria-label^="Question 2,"]', 400);
  ok(await has('文脈規定'), 'sheet: jumping to question 2 failed');
  await click('button[aria-label="Open the answer sheet"]', 400);
  await click('button[aria-label^="Question 9,"]', 400);
  await pickOpt(2);
  await click('button[aria-label="Open the answer sheet"]', 400);
  ok(await has('9 / 9 answered'), 'sheet: should count 9 answered');
  await click('button:has-text("もどる")', 300);
  await click('button[aria-label="Open the answer sheet"]', 400);
  await click('button:has-text("Submit")', 600);
  await at('08-break');
  ok(await has('Start section 2'), 'break: next section button missing');
  ok(await has('Sound check'), 'break: the only break comes before listening, so it has the sound check');
  await click('button[aria-label="Play the test sound"]', 300);
  ok(await has('Playing the test sound'), 'break: sound check should be running');
  await until(SOUND ? '聞こえましたか' : '音声を再生できません', 8000);
  await at('09-break-checked');
  if (SOUND) ok((await audio()).some((a) => a.ev === 'start' && Math.abs(a.d - 3540) < 120), 'break: the test sound should have played');
  const l0 = Date.now();
  await click('button:has-text("Start section 2")', 300);
  await at('10-l1');
  ok(await has('課題理解'), 'listening: first item type missing');
  ok((await page.locator('button[aria-label="Open the answer sheet"]').count()) === 0, 'listening: no answer sheet button');
  await page.waitForTimeout(1500);
  ok((await has('no sound here')) === !SOUND, 'listening: the band should say so only when there is no sound');
  await pickOpt(3);
  await until('概要理解', 90000);
  await page.waitForTimeout(300);
  await at('11-l2');
  ok((await page.locator('button[aria-label^="Choice"]').count()) === 4, 'listening: 概要理解 should offer four spoken choices');
  await pickOpt(4);
  await until('即時応答', 90000);
  await page.waitForTimeout(300);
  await at('12-l3');
  ok((await page.locator('button[aria-label^="Reply"]').count()) === 3, 'listening: 即時応答 should offer three replies');
  await pickOpt(3);
  await until('Correct answers', 50000);
  await page.waitForTimeout(400);
  const took = Date.now() - l0;
  console.log('   listening section took ' + Math.round(took / 1000) + ' s');
  if (SOUND) {
    // the seven listening clips, in order, each starting only after the one before it has ended
    const starts = (await audio()).filter((a) => a.ev === 'start').slice(-7);
    const want = mockClips;
    ok(starts.length === 7 && starts.every((a, n) => Math.abs(a.d - want[n]) < 120), 'listening: wrong clips or order: ' + JSON.stringify(starts.map((a) => a.d)));
    ok(starts.every((a, n) => n === 0 || a.t >= starts[n - 1].t + starts[n - 1].d), 'listening: a clip started before the one before it had ended: ' + JSON.stringify(starts));
    ok((await audio()).filter((a) => a.ev === 'stop').length === 0, 'listening: no clip should be cut off in a clean run');
    ok(took > listeningMs - 6500 && took < listeningMs + 9500, 'listening: expected about ' + Math.round(listeningMs / 1000) + ' s with sound, took ' + took);
  } else {
    ok((await audio()).length === 0, 'no clip should start when sound is off');
    ok(took < 50000, 'listening: without sound the stand-in timing should be short, took ' + took);
  }
  await at('13-result');
  ok(await has('Correct answers'), 'result: not reached');
  const h1 = ((await page.locator('h1').first().textContent()) || '').trim();
  ok(h1 === '9', 'result: expected 9 correct, got ' + h1);
  ok(await has('3 mistakes saved to your notebook'), 'result: saved line wrong');
  await click('button:has-text("Answers and reasons")', 500);
  await at('14-answers-1');
  ok((await page.locator('[role=tab]').count()) === 4, 'answers: four areas expected');
  ok(await has('あなたの答え：座礁'), 'answers: wrong answer for question 2 missing');
  await click('[role=tab] >> nth=1', 400);
  await at('15-answers-2');
  ok(await has('週に一度は'), 'answers: grammar tab should show the sentence-order answer');
  await click('[role=tab] >> nth=2', 400);
  await at('16-answers-3');
  ok(await has('意欲の面での効果'), 'answers: reading tab should show the 統合理解 answer');
  await click('[role=tab] >> nth=3', 400);
  await click('button:has-text("Show the script") >> nth=1', 400);
  await at('17-answers-4');
  ok(await has('最近の若者は本を読まない'), 'answers: script did not open');
  await click('button[aria-label="Back to the result"]', 400);
  await click('a:has-text("Close")', 600);
  await at('18-tab-taken');
  ok(await has('Last result'), 'tab: result summary missing after the run');
  await click('nav a:has-text("Notebook")', 600);
  await at('19-notebook');
  const nb = await body();
  ok(nb.includes('概要理解') && nb.includes('本を読ませる方法'), 'notebook: listening mistake missing');
  ok(nb.includes('文の文法1') && nb.includes('なりに'), 'notebook: grammar mistake missing');
  ok(nb.includes('文脈規定') && nb.includes('座礁'), 'notebook: vocabulary mistake missing');
  await click('nav a:has-text("Mock exam")', 600);
  await click('a:has-text("Result")', 600);
  await at('20-result-again');
  ok(await has('Correct answers'), 'tab: Result link should reopen the result');
  await click('a[aria-label="Back to the mock exam tab"]', 600);
  await click('a:has-text("Again")', 600);
  await at('21-again-briefing');
  ok(await has('HOW IT RUNS'), 'again: should restart at the briefing');
  await click('button:has-text("Start section 1")', 400);
  await click('button[aria-label="Quit the mock"]', 400);
  await at('22-quit-sheet');
  ok(await has('模試を中止しますか'), 'quit: confirm sheet missing');
  await click('a:has-text("Quit")', 600);
  await at('23-tab-after-quit');
  ok(await has('Last result'), 'tab: quitting a second attempt should keep the last result');
  await click('a:has-text("Result")', 600);
  ok(await has('Correct answers') && await has('7 / 9'), 'tab: the kept result should reopen with its scores');
  await click('a[aria-label="Back to the mock exam tab"]', 600);
  // backing out of the briefing without starting keeps it too
  await click('a:has-text("Again")', 600);
  ok(await has('HOW IT RUNS'), 'again: briefing expected');
  await click('a[aria-label="Back to the mock exam tab"]', 600);
  await at('24-tab-after-back');
  ok(await has('Last result'), 'tab: backing out of the briefing should keep the last result');

  const noisy = logs.filter((l) => !/Download the React DevTools/.test(l));
  console.log('console problems: ' + JSON.stringify(noisy.slice(0, 10)));
  console.log((SOUND ? 'with sound: ' : 'silent fallback: ') + (fails === 0 && noisy.length === 0 ? 'MOCK E2E PASS' : `MOCK E2E FAIL (${fails} failed checks, ${noisy.length} console problems)`));
  await browser.close();
})().catch((e) => { console.error('MOCK E2E CRASH', e); process.exit(1); });
